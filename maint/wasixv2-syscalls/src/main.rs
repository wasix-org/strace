//! Run from the strace root with the pinned codegen/wit directory as argument.
use std::{collections::BTreeMap, fs, path::Path};
use wasixv2_codegen::{
    Target,
    ir::{Function, Model},
    parse::parse_path,
};

fn slots(f: &Function) -> usize {
    f.params.len() + f.merged_i64.len()
}

fn generate(model: &Model) -> String {
    // Borrow decoder classifications, never syscall numbers or argument counts.
    let mut decoders = BTreeMap::new();
    for path in [
        "src/linux/32/syscallent.h",
        "src/linux/32/syscallent-common-32.h",
        "src/linux/generic/syscallent-common.h",
    ] {
        for line in fs::read_to_string(
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("../..")
                .join(path),
        )
        .unwrap()
        .lines()
        {
            if !line.starts_with('[') {
                continue;
            }
            let Some((_, rhs)) = line.split_once("= {") else {
                continue;
            };
            let fields: Vec<_> = rhs.split(',').map(str::trim).collect();
            if fields.len() < 4 {
                continue;
            }
            let name = rhs.split('"').nth(1).expect("syscall name");
            decoders.insert(
                name.to_string(),
                (fields[1].to_string(), fields[2].to_string()),
            );
        }
    }
    let mut calls = BTreeMap::new();
    for f in model.interfaces.iter().flat_map(|i| &i.functions) {
        if let Some(nr) = f.nr {
            calls.entry(nr).or_insert(f);
        }
    }
    let mut out = String::from("/* Generated by maint/wasixv2-syscalls from ABI 07cd32e. */\n");
    for (nr, f) in calls {
        assert!(slots(f) <= 6, "{} exceeds syscall-info slots", f.name);
        let name = f
            .sys_name
            .as_ref()
            .unwrap_or(&f.import_name)
            .replace('-', "_");
        let (flags, decoder) = match name.as_str() {
            // These imports are explicitly direct i64 in the WASIX ABI.
            "lseek" => ("TD".into(), "SEN(lseek)".into()),
            "mmap" => ("TM|SI".into(), "SEN(mmap)".into()),
            _ => decoders
                .get(&name)
                .cloned()
                .unwrap_or(("0".into(), "SEN(printargs)".into())),
        };
        // Parameter names document pair ordering alongside the generated count.
        let params = f
            .params
            .iter()
            .map(|p| {
                if f.merged_i64.iter().any(|m| m.param == p.name) {
                    format!("{}:{:?}", p.name, f.split_order(&p.name))
                } else {
                    p.name.clone()
                }
            })
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "/* {params} */\n[{nr}] = {{ {}, {flags}, {decoder}, \"{name}\" }},\n",
            slots(f)
        ));
    }
    out
}

fn main() {
    let wit = std::env::args()
        .nth(1)
        .expect("usage: generator CODEGEN/wit");
    let model = parse_path(Path::new(&wit), Target::WASM32).unwrap();
    print!("{}", generate(&model));
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn typed_slot_layout_matches_ptrace_transport() {
        let model = parse_path(
            Path::new(&std::env::var("WASIXV2_WIT").unwrap()),
            Target::WASM32,
        )
        .unwrap();
        let out = generate(&model);
        for entry in [
            "[62] = { 3, TD, SEN(lseek), \"lseek\" }",
            "[222] = { 6, TM|SI, SEN(mmap), \"mmap\" }",
            "[67] = { 5, TD, SEN(pread), \"pread64\" }",
            "[47] = { 6, TD, SEN(fallocate), \"fallocate\" }",
        ] {
            assert!(out.contains(entry), "missing {entry}");
        }
        assert!(!out.contains("SEN(llseek)"));
        assert!(!out.contains("SEN(mmap_pgoff)"));
        assert!(!out.contains("SEN(clock_gettime32)"));
    }
}
